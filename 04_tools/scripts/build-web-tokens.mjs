/**
 * Web design token pipeline.
 *
 * 01_core_hexin/packages/design/src/tokens.css used to be hand-written. Nothing
 * derived it from tokens.json, so it drifted: shadow-card became a two-layer
 * value the master never defined, and shadow-overlay flipped from an upward
 * offset to a downward one at double the opacity. A hand-maintained copy of a
 * source of truth is not a source of truth.
 *
 * Sources of truth (read only):
 *   01_core_hexin/packages/design/src/tokens.json
 *   01_core_hexin/packages/design/src/mobile-platforms.json
 *
 * Generated (never hand-edited):
 *   01_core_hexin/packages/design/src/tokens.css
 *   01_core_hexin/packages/design/src/Token.ts
 *
 * Run:  npm run build:web-tokens
 * Check: npm run build:web-tokens -- --check   (exits 1 if the file is stale)
 *
 * Naming note: Web variable names are kept exactly as they were. The mini
 * program uses a different convention (--sw-text-muted vs --sw-muted,
 * --sw-radius-small vs --sw-radius-sm). Unifying them means touching 554 call
 * sites and is a separate task with its own codemod. What matters here is one
 * source of truth, not identical spelling.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = join(ROOT, '01_core_hexin/packages/design/src/tokens.css');
const TOKEN_OUT = join(ROOT, '01_core_hexin/packages/design/src/Token.ts');

const t = JSON.parse(readFileSync(join(ROOT, '01_core_hexin/packages/design/src/tokens.json'), 'utf8'));
const platforms = JSON.parse(readFileSync(join(ROOT, '01_core_hexin/packages/design/src/mobile-platforms.json'), 'utf8'));

const CHECK_ONLY = process.argv.includes('--check');

/** Web renders token pt values as px, then expresses them in rem at a 16px root. */
const rem = (pt) => (pt === 0 ? '0' : `${pt / 16}rem`);

/**
 * Family names containing a space are quoted. Unquoted multi-word names are
 * legal CSS but fragile, and the hand-written file quoted them — dropping the
 * quotes would be an unrelated behaviour change smuggled in by the pipeline.
 */
const quoteFamilies = (stack) =>
  stack
    .split(',')
    .map((name) => name.trim())
    .map((name) => (name.includes(' ') && !name.startsWith("'") ? `'${name}'` : name))
    .join(', ');

/** elevation entries are unit-neutral; Web reads them as px. */
function shadow(name) {
  const e = t.elevation[name];
  if (!e) throw new Error(`elevation.${name} missing from tokens.json`);
  const [r, g, b] = e.color;
  return `${e.x}px ${e.y}px ${e.blur}px rgba(${r}, ${g}, ${b}, ${e.alpha})`;
}

const c = t.color;
const type = t.typography;
const mobileNavHeight = (platform) => platform.wingCodeButtonSize - platform.wingCodeProtrusion + t.spacing['3'];

/** Dark mode overrides are identical in both places, so build them once. */
