if (CHECK_ONLY) {
  const stale = [[OUT, css], [TOKEN_OUT, tokenSource]].filter(([file, expected]) => readFileSync(file, 'utf8') !== expected);
  if (stale.length > 0) {
    console.error(`design token artifacts are stale: ${stale.map(([file]) => file.slice(ROOT.length + 1)).join(', ')}`);
    process.exit(1);
  }
  console.log('web design token artifacts: current');
  process.exit(0);
}

writeFileSync(OUT, css);
writeFileSync(TOKEN_OUT, tokenSource);
console.log(`tokens.css  ${(css.length / 1024).toFixed(1)}KB`);
