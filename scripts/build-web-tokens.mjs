/**
 * Web design token pipeline.
 *
 * packages/design/src/token/Tokens.css used to be hand-written. Nothing
 * derived it from tokens.json, so it drifted: shadow-card became a two-layer
 * value the master never defined, and shadow-overlay flipped from an upward
 * offset to a downward one at double the opacity. A hand-maintained copy of a
 * source of truth is not a source of truth.
 *
 * Sources of truth (read only):
 *   packages/design/src/tokens.json
 *   packages/design/src/mobile-platforms.json
 *
 * Generated (never hand-edited):
 *   packages/design/src/token/Tokens.css
 *   packages/design/src/token/Tailwind.css
 *   packages/design/src/token/Token.ts
 *
 * Run:  npm run build:web-tokens
 * Check: npm run build:web-tokens -- --check   (exits 1 if the file is stale)
 *
 * The generated Tailwind adapter publishes semantic colour tokens. Product code
 * therefore uses names such as bg-surface and text-muted instead of maintaining
 * a second palette through framework colour names. Keeping the adapter separate
 * prevents non-Tailwind applications from parsing framework-only at-rules.
 */
