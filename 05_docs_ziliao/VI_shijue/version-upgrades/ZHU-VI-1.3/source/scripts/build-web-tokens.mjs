/**
 * Web design token pipeline.
 *
 * packages/design/src/tokens.css used to be hand-written. Nothing
 * derived it from tokens.json, so it drifted: shadow-card became a two-layer
 * value the master never defined, and shadow-overlay flipped from an upward
 * offset to a downward one at double the opacity. A hand-maintained copy of a
 * source of truth is not a source of truth.
 *
 * Sources of truth (read only):
 *   packages/design/src/tokens.json
 *   packages/design/src/mobile-platforms.json
 *
 * Generated (never hand-edited):
 *   packages/design/src/tokens.css
 *   packages/design/src/Token.ts
 *
 * Run:  node 04_tools/scripts/build-web-tokens.mjs
 * Check: node 04_tools/scripts/build-web-tokens.mjs --check   (exits 1 if stale)
 *
 * Naming note: Web variable names are kept exactly as they were. The mini
 * program uses a different convention (--sw-text-muted vs --sw-muted,
 * --sw-radius-small vs --sw-radius-sm). Unifying them means touching 554 call
 * sites and is a separate task with its own codemod. What matters here is one
 * source of truth, not identical spelling.
 */
